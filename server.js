app.post('/tasks/run', authenticate, (req, res) => {
  const { taskId, instruction = '' } = req.body;
  if (!taskId) {
    return res.status(400).json({ success: false, error: 'Missing taskId' });
  }

  console.log(`[TASK TRIGGER] Starting task ${taskId}: "${instruction}"`);
  const executorScript = fs.existsSync('/app/task_executor.py') 
    ? '/app/task_executor.py' 
    : path.join(__dirname, 'task_executor.py');

  const child = spawn('python3', [executorScript, 'run', taskId, instruction], {
    detached: true,
    stdio: 'ignore'
  });
  child.unref();

  res.json({
    success: true,
    taskId,
    status: 'triggered',
    message: 'Task runner launched immediately in background.'
  });
});

// 4. Python Script Execution Endpoint
app.post('/python', authenticate, (req, res) => {
  const { code, timeout = 30000 } = req.body;

  if (!code || typeof code !== 'string') {
    return res.status(400).json({
      success: false,
      error: 'Missing python code string'
    });
  }

  const tempFile = path.join(os.tmpdir(), `script_${Date.now()}_${Math.random().toString(36).substring(7)}.py`);
  fs.writeFileSync(tempFile, code, 'utf-8');

  const startTime = Date.now();
  exec(
    `python3 "${tempFile}"`,
    {
      shell: '/bin/bash',
      timeout: Math.min(Number(timeout) || 30000, 120000),
      maxBuffer: 10 * 1024 * 1024
    },
    (error, stdout, stderr) => {
      const durationMs = Date.now() - startTime;
      try { fs.unlinkSync(tempFile); } catch (e) {}

      res.json({
        success: !error,
        stdout: (stdout || '').trim(),
        stderr: (stderr || '').trim(),
        exitCode: error ? (error.code ?? 1) : 0,
        durationMs
      });
    }
  );
});

// 5. Vision AI Analysis Endpoint (Direct BLIP + PyTesseract OCR)
app.post('/vision/analyze', authenticate, (req, res) => {
  const { image_base64, image_url, timeout = 30000 } = req.body;
  if (!image_base64 && !image_url) {
    return res.status(400).json({ success: false, error: 'Missing image_base64 or image_url' });
  }

  const tempImg = path.join(os.tmpdir(), `vision_${Date.now()}_${Math.random().toString(36).substring(7)}.jpg`);
  try {
    if (image_base64) {
      const cleanB64 = image_base64.replace(/^data:image\/[a-z]+;base64,/, '');
      fs.writeFileSync(tempImg, Buffer.from(cleanB64, 'base64'));
    }
  } catch (err) {
    return res.status(500).json({ success: false, error: 'Failed to write image: ' + err.message });
  }

  const runnerCmd = image_url 
    ? `/root/vision_venv/bin/python3 /root/vision_analyzer.py analyze_url "${image_url.replace(/"/g, '\\"')}"`
    : `/root/vision_venv/bin/python3 /root/vision_analyzer.py analyze_file "${tempImg}"`;

  exec(
    runnerCmd,
    {
      shell: '/bin/bash',
      timeout: Math.min(Number(timeout) || 30000, 60000),
      maxBuffer: 5 * 1024 * 1024
    },
    (error, stdout, stderr) => {
      try { if (fs.existsSync(tempImg)) fs.unlinkSync(tempImg); } catch (e) {}
      if (error) {
        return res.status(500).json({ success: false, error: (stderr || error.message).trim() });
      }
      try {
        const result = JSON.parse(stdout.trim());
        res.json(result);
      } catch (e) {
        res.json({ success: false, error: 'Failed to parse vision output', raw: stdout });
      }
    }
  );
});

// ================= 📱 ANDROID COMPANION DEVICE BRIDGE (WEBSOCKET) =================
const server = http.createServer(app);
const wss = new WebSocketServer({ server, path: '/device-bridge' });
const activeDevices = new Map();

wss.on('connection', (ws, req) => {
  let deviceId = 'dev_' + Date.now().toString(36);
  const ip = req.socket.remoteAddress;
  console.log(`[DEVICE BRIDGE] New connection from ${ip}`);

  ws.on('message', (msgRaw) => {
    try {
      const data = JSON.parse(msgRaw.toString());
      if (data.type === 'device_register') {
        const mfr = (data.manufacturer || 'Android').replace(/\s+/g, '_');
        const model = (data.device_model || 'Device').replace(/\s+/g, '_');
        deviceId = `${mfr}_${model}`;
        activeDevices.set(deviceId, {
          ws,
          info: data,
          lastSeen: Date.now(),
          pending: new Map()
        });
        console.log(`[DEVICE BRIDGE] Registered: ${deviceId} (a11y: ${data.accessibility_enabled})`);
        ws.send(JSON.stringify({ type: 'registered', deviceId, status: 'connected' }));
      } else if (data.id && activeDevices.has(deviceId)) {
        const dev = activeDevices.get(deviceId);
        if (dev.pending && dev.pending.has(data.id)) {
          const resolve = dev.pending.get(data.id);
          dev.pending.delete(data.id);
          resolve(data);
        }
      }
    } catch (e) {
      console.warn('[DEVICE BRIDGE] Message parsing error:', e);
    }
  });

  ws.on('close', () => {
    console.log(`[DEVICE BRIDGE] Disconnected: ${deviceId}`);
    activeDevices.delete(deviceId);
  });
});

// Device Control REST API
app.post('/device/command', authenticate, async (req, res) => {
  const { command, args = {}, timeout = 10000, deviceId } = req.body;
  if (!command) {
    return res.status(400).json({ success: false, error: 'Missing command' });
  }

  let targetDevice = null;
  if (deviceId && activeDevices.has(deviceId)) {
    targetDevice = activeDevices.get(deviceId);
  } else if (activeDevices.size > 0) {
    targetDevice = Array.from(activeDevices.values())[0];
  }

  if (!targetDevice || targetDevice.ws.readyState !== 1) {
    return res.status(503).json({
      success: false,
      error: 'No active HoloCompanion Android device connected to bridge.'
    });
  }

  const reqId = 'req_' + Date.now() + '_' + Math.random().toString(36).substring(7);
  const payload = { id: reqId, command, ...args };

  const promise = new Promise((resolve) => {
    const timer = setTimeout(() => {
      targetDevice.pending.delete(reqId);
      resolve({ success: false, error: 'Device response timed out after ' + timeout + 'ms' });
    }, timeout);

    targetDevice.pending.set(reqId, (resp) => {
      clearTimeout(timer);
      resolve(resp);
    });
  });

  try {
    targetDevice.ws.send(JSON.stringify(payload));
    const result = await promise;
    res.json(result);
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

